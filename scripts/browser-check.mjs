import { mkdir, writeFile } from "node:fs/promises";
const tabs = await (await fetch("http://127.0.0.1:9222/json/list")).json();
const ws = new WebSocket(tabs.find(t => t.type === "page").webSocketDebuggerUrl);
await new Promise(r => ws.addEventListener("open", r, { once: true }));
let sequence = 0; const pending = new Map();
ws.addEventListener("message", event => { const m = JSON.parse(event.data); if (m.id) { pending.get(m.id)?.(m); pending.delete(m.id); } });
const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++sequence; pending.set(id, m => m.error ? reject(new Error(m.error.message)) : resolve(m.result)); ws.send(JSON.stringify({ id, method, params })); });
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: process.env.CHECK_URL || "http://localhost:3000" });
await new Promise(r => setTimeout(r, 5500));
await send("Runtime.evaluate", { expression: `Array.from(document.querySelectorAll('button')).find(b=>b.textContent.includes('Start your Quorum'))?.click()` });
await new Promise(r => setTimeout(r, 600));
await mkdir("artifacts", { recursive: true });
const screenshot = await send("Page.captureScreenshot", { format: "png" });
await writeFile(`artifacts/${process.argv[2] || "browser"}.png`, Buffer.from(screenshot.data, "base64"));
const result = await send("Runtime.evaluate", { expression: `({title:document.title,text:document.body.innerText.slice(0,4500),width:innerWidth,scrollWidth:document.documentElement.scrollWidth})`, returnByValue: true });
console.log(JSON.stringify(result.result.value));
ws.close();
